#!/usr/bin/env bash
# Resolve phase1.images (repo:tag) to phase1.lock (repo@sha256:...). Runs in CI, never in the
# agent sandbox (needs registry access). Needs skopeo. Usage: resolve_phase1_digests.sh [out]
set -euo pipefail
cd "$(dirname "$0")/.."
img=deploy/enterprise/images/phase1.images
out=${1:-deploy/enterprise/images/phase1.lock}
tmp=$(mktemp)
echo "# Generated by scripts/resolve_phase1_digests.sh from phase1.images. Do not hand-edit." > "$tmp"
while read -r ref; do
  case "$ref" in ''|'#'*) continue ;; esac
  d=$(skopeo inspect --raw "docker://$ref" | sha256sum | cut -d' ' -f1)
  echo "${ref%:*}@sha256:$d" >> "$tmp"
done < "$img"
python3 scripts/check_phase1_lock.py --strict "$tmp" "$img"
mv "$tmp" "$out"
cat "$out"
