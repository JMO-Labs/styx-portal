#!/usr/bin/env python3
"""Render static local raw-block PVs and the CephCluster for Rook-Ceph from the NVMe inventory.

Refuses anything that could point Ceph at an OS disk or an unstable device
name. Usage: gen_nvme_pvs.py [--inventory FILE] [--output FILE] [--cluster-output FILE]
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DIR = ROOT / "deploy/enterprise/rook-ceph"
PREFIX = "/dev/disk/by-id/nvme-"
BY_ID = re.compile(r"/dev/disk/by-id/nvme-[A-Za-z0-9._-]+")
STORAGE_CLASS = "local-nvme"
# Harbor prefix is a placeholder, overridden per site. Digest = multi-arch index.
CEPH_IMAGE = (
    "harbor.example.internal/quay.io/ceph/ceph:v20.2.5"
    "@sha256:4337ac8ac81d40df136e5eac92ca53bb52360a5e039f3d1f7935e729eb5ef42c"
)
OSD_CPU_BUDGET = 4  # cores per node; request = budget / NVMe-per-node
OSD_MEMORY = "8Gi"
CLUSTER_HEADER = (
    "# Generated by scripts/enterprise/gen_nvme_pvs.py from nvme-inventory.yaml. Do not edit.\n"
)
HEADER = (
    "# Generated by scripts/enterprise/gen_nvme_pvs.py from nvme-inventory.yaml. Do not edit.\n"
)


class InventoryError(ValueError):
    pass


def _name(host: str, path: str) -> str:
    # Serial = text after the last "_" of the by-id name; stable across boots.
    serial = re.sub(r"[^a-z0-9]+", "-", path.rsplit("_", 1)[-1].lower()).strip("-")
    return f"{STORAGE_CLASS}-{host}-{serial}"


def build(inv: dict) -> list[dict]:
    pvs, paths, names = [], set(), set()
    os_disks = {n.get("os_disk") for n in inv.get("nodes") or []} - {None}
    for node in inv.get("nodes") or []:
        host = node.get("hostname")
        if not host:
            raise InventoryError("node without hostname")
        disks = node.get("nvme") or []
        if not disks:
            raise InventoryError(f"{host}: no NVMe disks listed")
        os_disk = node.get("os_disk")
        for d in disks:
            for key in ("path", "size"):
                if key not in d:
                    raise InventoryError(f"{host}: disk entry missing '{key}'")
        for d in sorted(disks, key=lambda d: d["path"]):
            path = d["path"]
            if not isinstance(path, str) or not BY_ID.fullmatch(path) or ".." in path.split("/"):
                raise InventoryError(
                    f"{host}: {path} must be under {PREFIX}* (by-id, not kernel names)"
                )
            if path == os_disk or path in os_disks:
                raise InventoryError(f"{host}: {path} equals os_disk; refusing to use the OS disk")
            if path in paths:
                raise InventoryError(f"{host}: duplicate path {path}")
            paths.add(path)
            name = _name(host, path)
            if name in names:
                raise InventoryError(f"{host}: duplicate PV name {name} (serial collision)")
            names.add(name)
            pvs.append(
                {
                    "apiVersion": "v1",
                    "kind": "PersistentVolume",
                    "metadata": {"name": name},
                    "spec": {
                        "capacity": {"storage": str(d["size"])},
                        "accessModes": ["ReadWriteOnce"],
                        "volumeMode": "Block",
                        "storageClassName": STORAGE_CLASS,
                        "persistentVolumeReclaimPolicy": "Retain",
                        "local": {"path": path},
                        "nodeAffinity": {
                            "required": {
                                "nodeSelectorTerms": [
                                    {
                                        "matchExpressions": [
                                            {
                                                "key": "kubernetes.io/hostname",
                                                "operator": "In",
                                                "values": [host],
                                            }
                                        ]
                                    }
                                ]
                            }
                        },
                    },
                }
            )
    if not pvs:
        raise InventoryError("inventory has no nodes")
    return pvs


def render(inv: dict) -> str:
    docs = (yaml.safe_dump(pv, sort_keys=False) for pv in build(inv))
    return HEADER + "---\n" + "---\n".join(docs)


def _device_set(node: dict) -> dict:
    host = node["hostname"]
    sizes = {str(d["size"]) for d in node["nvme"]}
    if len(sizes) != 1:
        raise InventoryError(f"{host}: mixed NVMe sizes {sorted(sizes)}")
    affinity = {
        "requiredDuringSchedulingIgnoredDuringExecution": {
            "nodeSelectorTerms": [
                {
                    "matchExpressions": [
                        {"key": "kubernetes.io/hostname", "operator": "In", "values": [host]}
                    ]
                }
            ]
        }
    }
    return {
        "name": host,
        "count": len(node["nvme"]),
        "portable": False,
        "placement": {"nodeAffinity": affinity},
        "volumeClaimTemplates": [
            {
                "metadata": {"name": "data"},
                "spec": {
                    "resources": {"requests": {"storage": sizes.pop()}},
                    "storageClassName": STORAGE_CLASS,
                    "volumeMode": "Block",
                    "accessModes": ["ReadWriteOnce"],
                },
            }
        ],
    }


def build_cluster(inv: dict) -> dict:
    build(inv)  # validate inventory
    nodes = inv["nodes"]
    per_node = {len(n["nvme"]) for n in nodes}
    cpu = "2"
    if len(per_node) == 1:
        cpu = str(max(1, OSD_CPU_BUDGET // per_node.pop()))
    return {
        "apiVersion": "ceph.rook.io/v1",
        "kind": "CephCluster",
        "metadata": {"name": "rook-ceph", "namespace": "rook-ceph"},
        "spec": {
            "cephVersion": {"image": CEPH_IMAGE, "allowUnsupported": False},
            "dataDirHostPath": "/var/lib/rook",
            "skipUpgradeChecks": False,
            "continueUpgradeAfterChecksEvenIfNotHealthy": False,
            "removeOSDsIfOutAndSafeToRemove": False,
            "mon": {"count": 3, "allowMultiplePerNode": False},
            "mgr": {"count": 2, "allowMultiplePerNode": False},
            "disruptionManagement": {"managePodBudgets": True},
            "priorityClassNames": {
                "osd": "system-node-critical",
                "mon": "system-node-critical",
                "mgr": "system-cluster-critical",
            },
            "cephConfig": {
                "global": {"osd_scrub_begin_hour": "1", "osd_scrub_end_hour": "5"},
            },
            "resources": {
                "osd": {
                    "requests": {"cpu": cpu, "memory": OSD_MEMORY},
                    "limits": {"memory": OSD_MEMORY},
                }
            },
            "storage": {
                "useAllNodes": False,
                "useAllDevices": False,
                "storageClassDeviceSets": [_device_set(n) for n in nodes],
            },
        },
    }


def render_cluster(inv: dict) -> str:
    return CLUSTER_HEADER + yaml.safe_dump(build_cluster(inv), sort_keys=False)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--inventory", type=Path, default=DIR / "nvme-inventory.yaml")
    ap.add_argument("--output", type=Path, default=DIR / "local-pvs.yaml")
    ap.add_argument("--cluster-output", type=Path, default=DIR / "cephcluster.yaml")
    args = ap.parse_args(argv)
    try:
        inv = yaml.safe_load(args.inventory.read_text())
        text, cluster = render(inv), render_cluster(inv)
    except InventoryError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    args.output.write_text(text)
    args.cluster_output.write_text(cluster)
    return 0


if __name__ == "__main__":
    sys.exit(main())
